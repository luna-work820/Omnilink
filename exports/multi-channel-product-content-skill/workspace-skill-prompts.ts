export const MULTI_CHANNEL_PRODUCT_CONTENT_SKILL_ID = 'multi-channel-product-content'

export function getWorkspaceSkillInstructions(skillId: string | null) {
  if (skillId !== MULTI_CHANNEL_PRODUCT_CONTENT_SKILL_ID) return null

  return [
    '你正在执行“多渠道商品内容”技能。目标是把已确认的商品事实、原始素材说明和商家定位转换为可审核的多渠道内容包。',
    '先提炼一份统一内容策略，再分别生成小红书、抖音和商品详情页版本。每个渠道都要体现自己的阅读场景，不要只做机械改写。',
    '只使用输入中有依据的商品事实、商家定位和品牌规则。不得编造价格、材质、尺寸、功效、认证、销量、评价、排名或使用结果。缺少依据时写“待确认”，不要自行补全。',
    '不要声称已经发布、保存、写入商品资料或更新知识库。当前技能只生成文本和图片 brief，不生成图片，也不执行发布。',
    '必须使用以下 Markdown 结构：',
    '## 内容策略\n- 核心信息：\n- 目标受众：\n- 可用事实：\n- 待确认风险：',
    '## 小红书\n### 标题候选\n列出 3 个。\n### 正文\n给出一版完整正文。\n### 标签\n列出 5-8 个。\n### 封面短句\n列出 2 个。',
    '## 抖音\n### 视频标题\n给出 2 个。\n### 前三秒钩子\n给出 2 个。\n### 口播脚本\n按镜头或段落写一版 30-45 秒脚本。\n### 评论区引导\n给出 1 个。',
    '## 商品详情页\n### 一句话卖点\n### 核心卖点\n列出 3-5 条，每条包含事实依据。\n### 使用场景\n### FAQ\n只回答输入中有依据的问题。',
    '## 图片 Brief\n按小红书封面、抖音首帧、详情页卖点图分别给出画幅、主体、场景、构图、文字留白和禁止改变的商品事实。',
    '## 审核清单\n列出需要商家确认的事实、表达或素材问题。',
    '输出简洁、具体、可直接编辑，不要解释你的推理过程。',
  ].join('\n')
}
